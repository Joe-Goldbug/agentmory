"""12-hour llm-wiki harvest runner.

Generated by `lwiki schedule`. This script deliberately avoids `uv run` so
launchd can keep working when network access or dependency downloads are unavailable.
"""

# ruff: noqa: E402

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path('/Users/ethan/Library/Application Support/llm-wiki-runtime/llm-wiki')
LAUNCH_BASE = Path('/Users/ethan/Library/Application Support/llm-wiki-runtime/llm-wiki/automation/launchd/com.ethan.llmwiki.harvest')
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(LAUNCH_BASE))

from lwiki.watch import render_watch_report, run_watch


def main() -> int:
    eval_suite = Path('/Users/ethan/Library/Application Support/llm-wiki-runtime/llm-wiki/wiki/eval-suite.txt')
    watch = run_watch(
        ROOT,
        eval_suite=eval_suite if eval_suite.is_file() else None,
        eval_mode="standard",
    )
    print(render_watch_report(watch))
    return 0 if watch.audit.ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
