"""12-hour llm-workmem harvest runner.

Generated by `lwm schedule`. This script deliberately avoids `uv run` so
launchd can keep working when network access or dependency downloads are unavailable.
"""

# ruff: noqa: E402

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path('/Users/ethan/Library/Application Support/llm-workmem-runtime/llm-workmem')
LAUNCH_BASE = Path('/Users/ethan/Library/Application Support/llm-workmem-runtime/llm-workmem/automation/launchd/com.ethan.lwm.harvest')
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(LAUNCH_BASE))

from lwm.watch import render_watch_report, run_watch


def main() -> int:
    eval_suite = Path('/Users/ethan/Library/Application Support/llm-workmem-runtime/llm-workmem/wiki/eval-suite.txt')
    watch = run_watch(
        ROOT,
        eval_suite=eval_suite if eval_suite.is_file() else None,
        eval_mode="standard",
    )
    print(render_watch_report(watch))
    return 0 if watch.audit.ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
