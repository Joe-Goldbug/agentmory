def install_kiro(home: Path) -> HookInstall:
    # Keep the installer, registry discovery, and global adapter on one
    # canonical filename. A different filename would make an install appear
    # successful while `lwm hub tools probe` still reports Kiro as missing.
    steering_path = home / ".kiro" / "steering" / "llm-workmem.md"
    # Kiro's documented hooks are tool-use guards, not session lifecycle
    # hooks. Preserve the user's settings and let the local session observer
    # supply evidence rather than writing an invented setting schema.
    detail_settings = "steering: preserved settings; session observer enabled"
    _safe_replace(steering_path, KIRO_STEERING)
    return HookInstall(
        tool="kiro",
        config_path=steering_path,
        detail=detail_settings,
    )


def install_trae(home: Path) -> HookInstall:
    """Report the verified Trae fallback without inventing hook JSON."""

    target = home / ".traerules"
    return HookInstall(
        tool="trae",
        config_path=target,
        detail="no verified native hook; use .traerules plus the Trae session observer",
    )


def install_minimax(home: Path, *, root: Path | None = None) -> HookInstall:
    target = home / ".minimax" / "lwm-shell.sh"
    changed = _safe_replace(target, MINIMAX_SHELL_HOOK)
    target.chmod(0o755)

    mcp_path = home / ".minimax" / "mcp" / "mcp.json"
    _merge_local_mcp_server(
        mcp_path,
        canonical_data_root(root or Path.cwd()),
        home=home.resolve(),
        tool="minimax",
        integration="minimax-mcp",
    )
    return HookInstall(
        tool="minimax",
        config_path=target,
        detail=_render_status(changed, "shell-wrapper + MCP bridge"),
    )


def install_opencode(home: Path, *, root: Path) -> HookInstall:
    """Install OpenCode's plugin at one canonical user-owned path.

    A previously generated LLM-WorkMem plugin may still be registered from a
    source checkout. Migrate that known plugin only; unrelated user plugins
    remain untouched.
    """

    root = canonical_data_root(root)
    config_path = home / ".config" / "opencode" / "opencode.json"
    config = _load_json_object(config_path)
    plugins = config.get("plugin") if isinstance(config.get("plugin"), list) else []
    canonical = home / ".config" / "opencode" / "plugins" / "llm-workmem.ts"
    config_changed = False

    # The plugin is not the only OpenCode ownership pointer. Older installs
    # may still tell OpenCode to read the checkout through `references`; move
    # only the known WorkMem reference and preserve every unrelated entry.
    references = config.get("references")
    if isinstance(references, dict):
        for reference_name in ("llm-workmem", "lwm-workmem"):
            reference = references.get(reference_name)
            if not isinstance(reference, dict):
                continue
            reference_path = reference.get("path")
            if not isinstance(reference_path, str):
                continue
            if "llm-workmem" not in reference_path.lower() and "lwm-workmem" not in reference_path.lower():
                continue
            if reference_path == str(root):
                continue
            updated_reference = dict(reference)
            updated_reference["path"] = str(root)
            updated_references = dict(references)
            updated_references[reference_name] = updated_reference
            config["references"] = updated_references
            config_changed = True
            break

    def resolve_registered(value: str) -> Path:
        candidate = Path(value).expanduser()
        return candidate if candidate.is_absolute() else config_path.parent / candidate

    def is_lwm_plugin(path: Path) -> bool:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            return False
        return (
            ("LlmWorkmemPlugin" in text or "LlmWorkMemPlugin" in text)
            and "hub bridge" in text
        )

    def is_lwm_entry(value: object) -> bool:
        if not isinstance(value, str):
            return False
        lowered = value.lower()
        return "llm-workmem" in lowered or "lwm-workmem" in lowered

    registered_entry: str | None = next(
        (
            plugin
            for plugin in plugins
            if is_lwm_entry(plugin)
        ),
        None,
    )
    registered = resolve_registered(registered_entry) if registered_entry else None
    migrate_registered = registered is not None and (
        not registered.is_file() or is_lwm_plugin(registered)
    )

    if migrate_registered:
        target = canonical
        changed = _safe_replace(target, _opencode_plugin(root))
        replaced = False
        normalized_plugins: list[object] = []
        for plugin in plugins:
            if plugin == registered_entry:
                if not replaced:
                    normalized_plugins.append(str(canonical))
                    replaced = True
                continue
            normalized_plugins.append(plugin)
        if normalized_plugins != plugins:
            config["plugin"] = normalized_plugins
            config_changed = True
    elif registered is not None:
        target = registered
        changed = False
    else:
        target = canonical
        changed = _safe_replace(target, _opencode_plugin(root))
        config["plugin"] = [*plugins, str(canonical)]
        config_changed = True
    if config_changed:
        changed = _write_json(config_path, config) or changed
    return HookInstall("opencode", target, _render_status(changed, "lifecycle-plugin"))


def _render_status(changed: bool, kind: str) -> str:
    return f"{kind}: {'updated' if changed else 'already current'}"


def install_ide_hooks(
    home: Path,
    *,
    root: Path | None = None,
    tools: tuple[str, ...] = (
        "claude-code",
        "codex",
        "cursor",
        "kiro",
        "opencode",
        "trae",
        "minimax",
        "gemini-cli",
        "antigravity",
    ),
) -> list[HookInstall]:
    normalized_root = canonical_data_root(root or Path.cwd())
    installers = {
        "claude-code": lambda target_home: install_claude_code(target_home, root=normalized_root),
        "codex": lambda target_home: install_codex(target_home, root=normalized_root),
        "cursor": lambda target_home: install_cursor(target_home, root=normalized_root),
        "kiro": install_kiro,
        "opencode": lambda target_home: install_opencode(target_home, root=normalized_root),
        "trae": install_trae,
        "minimax": lambda target_home: install_minimax(target_home, root=normalized_root),
        "gemini-cli": lambda target_home: install_gemini_cli(
            target_home, root=normalized_root
        ),
        "antigravity": lambda target_home: install_antigravity(
            target_home, root=normalized_root
        ),
    }
    installed: list[HookInstall] = []
    for name in tools:
        installer = installers.get(name)
        if installer is None:
            continue
        installed.append(installer(home))
    return installed


