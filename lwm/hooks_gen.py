"""Level 1 native hook installers for IDEs that support them.

Most modern AI IDEs expose at least one of:

* a settings file with a ``hooks`` array (Claude Code)
* a global instructions directory with ``templates`` (Codex CLI <=0.x)
* a steering directory (Kiro)
* an extension that calls a binary on tool invocation (Trae vs IDE plugin)

For each we generate a small shim that pipes an event JSON to
``lwm hub record`` via stdin. The shim uses only the public CLI so the
truth source for the schema stays in one place.

Generation is *idempotent* and respects ``--dry-run`` from the caller.
The CLI surface is ``lwm hub install-ide-hooks``.
"""

from __future__ import annotations

import json
import shlex
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class HookInstall:
    tool: str
    config_path: Path
    detail: str


def _claude_hook_template(root: Path) -> dict:
    start = root / "adapters" / "hooks" / "claude_code_session_start.py"
    stop = root / "adapters" / "hooks" / "claude_code_stop.py"
    prefix = f"LWM_ROOT={shlex.quote(str(root))} \"$HOME/Library/Application Support/llm-workmem-runtime/app/venv/bin/python\""
    return {
        "SessionStart": [{"matcher": "", "hooks": [{"type": "command", "command": f"{prefix} {shlex.quote(str(start))}", "timeout": 15}]}],
        "Stop": [{"matcher": "", "hooks": [{"type": "command", "command": f"{prefix} {shlex.quote(str(stop))}", "timeout": 15}]}],
    }


CODEX_TEMPLATE_HOOK = "# BEGIN LWM hook\n[hook]\nname = lwm-record\non = session_start\ncommand = lwm hub record --tool=codex --project={cwd} --type=session_start --task={task} --importance=project\n# END LWM hook\n"


KIRO_STEERING = """---
title: LLM-WorkMem inbound hook
type: steering
---

When a session starts, pipe the session metadata into the central hub via:

``lwm hub record --tool=kiro --project=$PROJECT_PATH --type=session_start --task=$TASK --importance=project``

The hook file controlling this behaviour lives in
``~/.kiro/hooks/lwm.toml`` and is regenerated by ``lwm hub install-ide-hooks``.
"""


TRAE_HOOK = {
    "hooks": [
        {
            "matcher": "task_start",
            "type": "command",
            "command": "lwm hub record --tool=trae --project=$PROJECT_PATH --type=session_start --task=$TASK --importance=project",
        },
        {
            "matcher": "task_end",
            "type": "command",
            "command": "lwm hub record --tool=trae --project=$PROJECT_PATH --type=session_summary --task=$TASK --importance=project",
        },
    ]
}


MINIMAX_SHELL_HOOK = """#!/usr/bin/env zsh
# Generated by `lwm hub install-ide-hooks`.
#
# Source this file from zsh when Claude Code or a local shell needs to call the
# MiniMax API and leave a sanitized event trail in LLM-WorkMem.

lwm-minimax-chat() {
  local prompt="$*"
  local project="${PWD}"
  local root="${LWM_ROOT:-/Users/ethan/Library/Mobile Documents/com~apple~CloudDocs/Downloads/LLM-WorkMem}"
  local endpoint="${MINIMAX_API_ENDPOINT:-${MINIMAX_BASE_URL:-}}"
  local model="${MINIMAX_MODEL:-}"

  if [[ -z "$MINIMAX_API_KEY" ]]; then
    printf '%s\\n' "MINIMAX_API_KEY is not set" >&2
    return 2
  fi
  if [[ -z "$endpoint" ]]; then
    printf '%s\\n' "MINIMAX_API_ENDPOINT or MINIMAX_BASE_URL is not set" >&2
    return 2
  fi
  if [[ -z "$prompt" ]]; then
    printf '%s\\n' "usage: lwm-minimax-chat <prompt>" >&2
    return 2
  fi

  lwm hub record --root "$root" --tool=minimax --project="$project" --type=workflow_observation --task="MiniMax API call started" --tag=minimax --tag=api >/dev/null 2>&1

  local payload
  payload=$(python3 - "$model" "$prompt" <<'PY'
import json
import sys

model = sys.argv[1]
prompt = sys.argv[2]
print(json.dumps({"model": model, "messages": [{"role": "user", "content": prompt}]}))
PY
)

  curl -sS "$endpoint" \\
    -H "Authorization: Bearer $MINIMAX_API_KEY" \\
    -H "Content-Type: application/json" \\
    -d "$payload"
  local code="$?"

  if [[ "$code" == "0" ]]; then
    lwm hub record --root "$root" --tool=minimax --project="$project" --type=verification --task="MiniMax API call completed" --verification="curl exit 0" --tag=minimax --tag=api >/dev/null 2>&1
  else
    lwm hub record --root "$root" --tool=minimax --project="$project" --type=workflow_observation --task="MiniMax API call failed" --verification="curl exit $code" --tag=minimax --tag=api >/dev/null 2>&1
  fi
  return "$code"
}
"""


def _opencode_plugin(root: Path) -> str:
    quoted_root = json.dumps(str(root.resolve()))
    return f'''import type {{ Plugin }} from "@opencode-ai/plugin";

const root = {quoted_root};

export const LlmWorkMemPlugin: Plugin = async ({{ directory, $ }}) => {{
  const invoke = async (phase: "start" | "stop", event: unknown) => {{
    const data = event as {{ properties?: {{ info?: {{ id?: string }} }} }};
    const sessionId = String(data.properties?.info?.id ?? "");
    await $`lwm hub lifecycle ${{phase}} --tool opencode --project ${{directory}} --session-id ${{sessionId}} --root ${{root}} --source native-hook`.quiet();
  }};
  return {{
    event: async ({{ event }}) => {{
      if (event.type === "session.created") await invoke("start", event);
      if (event.type === "session.idle" || event.type === "session.deleted") await invoke("stop", event);
    }},
  }};
}};

export default LlmWorkMemPlugin;
'''


def _safe_replace(path: Path, body: str | bytes) -> bool:
    """Write *body* to *path*; return True if anything changed."""

    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_bytes() if path.is_file() else b""
    new_bytes = body.encode("utf-8") if isinstance(body, str) else body
    if existing == new_bytes:
        return False
    path.write_bytes(new_bytes)
    return True


def _write_json(path: Path, body: dict) -> bool:
    return _safe_replace(path, json.dumps(body, ensure_ascii=False, indent=2))


def _load_json_object(path: Path) -> dict:
    try:
        loaded = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
    except (OSError, json.JSONDecodeError):
        loaded = {}
    return loaded if isinstance(loaded, dict) else {}


def _is_lwm_hook(entry: object) -> bool:
    if not isinstance(entry, dict):
        return False
    hooks = entry.get("hooks")
    if not isinstance(hooks, list):
        return False
    return any(isinstance(item, dict) and "claude_code_" in str(item.get("command", "")) for item in hooks)


def install_claude_code(home: Path, *, root: Path | None = None) -> HookInstall:
    """Merge LWM lifecycle hooks into the real Claude settings file."""

    target = home / ".claude" / "settings.json"
    body = _load_json_object(target)
    hooks = body.get("hooks") if isinstance(body.get("hooks"), dict) else {}
    hooks = dict(hooks)
    for event, entries in _claude_hook_template((root or Path.cwd()).resolve()).items():
        current = hooks.get(event) if isinstance(hooks.get(event), list) else []
        hooks[event] = [entry for entry in current if not _is_lwm_hook(entry)] + entries
    body["hooks"] = hooks
    return HookInstall(
        tool="claude-code",
        config_path=target,
        detail=_render_status(_write_json(target, body), "settings hooks"),
    )


def install_codex(home: Path) -> HookInstall:
    target = home / ".codex" / "hooks.toml"
    return HookInstall(
        tool="codex",
        config_path=target,
        detail=_render_status(_safe_replace(target, CODEX_TEMPLATE_HOOK), "hook"),
    )


def install_kiro(home: Path) -> HookInstall:
    settings = home / ".kiro" / "settings.json"
    steering_path = home / ".kiro" / "steering" / "lwm.md"
    # Kiro's documented hooks are tool-use guards, not session lifecycle
    # hooks. Preserve the user's settings and let the local session observer
    # supply evidence rather than writing an invented setting schema.
    detail_settings = "steering: preserved settings; session observer enabled"
    _safe_replace(steering_path, KIRO_STEERING)
    return HookInstall(
        tool="kiro",
        config_path=settings,
        detail=detail_settings,
    )


def install_trae(home: Path) -> HookInstall:
    target = home / ".trae" / "hooks.json"
    return HookInstall(
        tool="trae",
        config_path=target,
        detail=_render_status(_write_json(target, TRAE_HOOK), "hooks"),
    )


def install_minimax(home: Path) -> HookInstall:
    target = home / ".minimax" / "lwm-shell.sh"
    changed = _safe_replace(target, MINIMAX_SHELL_HOOK)
    target.chmod(0o755)
    return HookInstall(
        tool="minimax",
        config_path=target,
        detail=_render_status(changed, "shell-wrapper"),
    )


def install_opencode(home: Path, *, root: Path) -> HookInstall:
    """Install OpenCode's documented local plugin without replacing config."""

    config_path = home / ".config" / "opencode" / "opencode.json"
    config = _load_json_object(config_path)
    plugins = config.get("plugin") if isinstance(config.get("plugin"), list) else []
    registered = next(
        (
            Path(plugin).expanduser()
            for plugin in plugins
            if isinstance(plugin, str) and "lwm-workmem" in plugin.lower()
        ),
        None,
    )
    target = registered or home / ".config" / "opencode" / "plugins" / "llm-workmem.ts"
    # Keep a real registered plugin's richer behavior intact. This prevents a
    # later install/schedule run from replacing it with the fallback template.
    changed = False if registered and target.is_file() else _safe_replace(target, _opencode_plugin(root))
    marker = str(target)
    if marker not in plugins:
        config["plugin"] = [*plugins, marker]
        changed = _write_json(config_path, config) or changed
    return HookInstall("opencode", target, _render_status(changed, "lifecycle-plugin"))


def _render_status(changed: bool, kind: str) -> str:
    return f"{kind}: {'updated' if changed else 'already current'}"


def install_ide_hooks(
    home: Path,
    *,
    root: Path | None = None,
    tools: tuple[str, ...] = ("claude-code", "codex", "kiro", "opencode", "trae", "minimax"),
) -> list[HookInstall]:
    installers = {
        "claude-code": lambda target_home: install_claude_code(target_home, root=(root or Path.cwd())),
        "codex": install_codex,
        "kiro": install_kiro,
        "opencode": lambda target_home: install_opencode(target_home, root=(root or Path.cwd())),
        "trae": install_trae,
        "minimax": install_minimax,
    }
    installed: list[HookInstall] = []
    for name in tools:
        installer = installers.get(name)
        if installer is None:
            continue
        installed.append(installer(home))
    return installed


