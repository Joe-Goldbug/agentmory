"""Small deterministic Retain/Recall/Reflect API for tools and MCP."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from lwm import inbox
from lwm.events import make_event
from lwm.project_id import record_project
from lwm.query import run_query


def retain(
    root: Path,
    *,
    tool: str,
    project_path: str,
    task: str,
    event_type: str = "workflow_observation",
    decisions: list[str] | None = None,
    changes: list[str] | None = None,
    verification: list[str] | None = None,
    open_questions: list[str] | None = None,
    session_id: str | None = None,
) -> dict[str, Any]:
    resolution = record_project(root, project_path)
    event = make_event(
        tool=tool,
        project_path=project_path,
        project_id=resolution.project_id,
        event_type=event_type,
        task=task,
        decisions=decisions,
        changes=changes,
        verification=verification,
        open_questions=open_questions,
        session_id=session_id,
        source={"kind": "retain"},
    )
    target = inbox.submit_event(root, event)
    return {"event": event, "path": str(target), "project_id": resolution.project_id}


def recall(root: Path, question: str, *, project_path: str | None = None, limit: int = 6) -> dict[str, Any]:
    report = run_query(root, question, mode="standard", limit=limit)
    return {
        "question": question,
        "project_path": project_path,
        "mode": report.mode,
        "hits": [
            {"path": hit.page.rel_path, "score": hit.score, "excerpt": hit.excerpt}
            for hit in report.hits
        ],
        "notes": list(report.notes),
    }


def reflect_project(root: Path, project_id: str) -> Path:
    """Write a compact state page with source and generation provenance."""

    events: list[dict[str, Any]] = []
    processed = root / "raw" / "events" / "processed"
    if processed.is_dir():
        for path in processed.rglob("*.json"):
            try:
                payload = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            if isinstance(payload, dict) and str(payload.get("project_id")) == project_id:
                events.append(payload)
    events.sort(key=lambda row: str(row.get("timestamp") or ""), reverse=True)
    target = root / "wiki" / "projects" / project_id / "STATE.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "---",
        f"title: Project State {project_id}",
        "type: project-state",
        f"project_id: {project_id}",
        f"updated: {datetime.now(timezone.utc).astimezone().isoformat(timespec='seconds')}",
        "sources: [raw/events/processed]",
        "---",
        "",
        f"# Project State: {project_id}",
        "",
        "## Recent Verified Work",
    ]
    for event in events[:12]:
        task = str(event.get("task") or event.get("event_type") or "(untitled)").replace("\n", " ")
        verification = "; ".join(str(item) for item in event.get("verification") or [])
        suffix = f" | verified: {verification}" if verification else ""
        lines.append(f"- {event.get('timestamp', 'unknown')} | {event.get('tool', 'unknown')} | {task}{suffix}")
    if not events:
        lines.append("- (no processed events)")
    lines.extend(["", "## Provenance", "- Generated by `lwm reflect` from processed event evidence.", ""])
    target.write_text("\n".join(lines), encoding="utf-8")
    return target


__all__ = ["recall", "reflect_project", "retain"]
