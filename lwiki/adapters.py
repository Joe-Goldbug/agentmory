"""Per-tool adapters that let IDEs and shells consume llm-wiki."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

MARKER_START = "<!-- LLM-WIKI:START -->"
MARKER_END = "<!-- LLM-WIKI:END -->"


@dataclass(frozen=True)
class AdapterReport:
    root: Path
    target: Path
    written: tuple[Path, ...]


@dataclass(frozen=True)
class AttachReport:
    root: Path
    project: Path
    written: tuple[Path, ...]


def _context_block(root: Path, *, project: Path | None = None) -> str:
    root = root.resolve()
    project_line = f"\nProject: `{project}`" if project else ""
    return f"""{MARKER_START}
# LLM Wiki Context

Use this llm-wiki as the shared workflow and memory source for this tool.{project_line}

Read order:
1. `{root / 'llms.txt'}` for compact context.
2. `{root / 'wiki' / 'purpose.md'}` for scope and guardrails.
3. `{root / 'wiki' / 'overview.md'}` for the current synthesis.
4. `{root / 'llms-full.txt'}` only when deeper context is needed.
5. `{root / 'llms.json'}` for programmatic page metadata.

Rules:
- Treat `raw/` as source evidence, not polished memory.
- Prefer `wiki/` pages that passed audit over raw snapshots.
- Keep local project facts local unless they should be promoted through review.
- After meaningful work, update or generate evidence that `lwiki harvest`, `lwiki watch`, or `lwiki audit` can consume.
{MARKER_END}
"""


def _shell_context(root: Path) -> str:
    root = root.resolve()
    return """#!/bin/zsh
# Generated by `lwiki adapters`. Source this file from zsh when you want
# shell commands that expose the shared llm-wiki context.

export LLM_WIKI_ROOT={root!r}

lwiki-root() {{
  printf '%s\\n' "$LLM_WIKI_ROOT"
}}

lwiki-open() {{
  open "$LLM_WIKI_ROOT/knowledge-digest.html"
}}

lwiki-status() {{
  cd "$LLM_WIKI_ROOT" && uv run --extra dev lwiki audit "$LLM_WIKI_ROOT" --eval-suite "$LLM_WIKI_ROOT/wiki/eval-suite.txt"
}}

lwiki-refresh() {{
  cd "$LLM_WIKI_ROOT" && uv run --extra dev lwiki watch "$LLM_WIKI_ROOT" --eval-suite "$LLM_WIKI_ROOT/wiki/eval-suite.txt"
}}

lwiki-context() {{
  sed -n '1,220p' "$LLM_WIKI_ROOT/llms.txt"
}}
""".format(root=str(root))


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")
    if path.suffix == ".sh":
        path.chmod(0o755)
    return path


def _merge_marked_block(path: Path, block: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.is_file() else ""
    if MARKER_START in existing and MARKER_END in existing:
        before = existing.split(MARKER_START, 1)[0].rstrip()
        after = existing.split(MARKER_END, 1)[1].lstrip()
        content = "\n\n".join(part for part in (before, block.rstrip(), after.rstrip()) if part)
    elif existing.strip():
        content = existing.rstrip() + "\n\n" + block.rstrip()
    else:
        content = block.rstrip()
    path.write_text(content + "\n", encoding="utf-8")
    return path


def _antigravity_global_paths(home: Path) -> tuple[Path, ...]:
    return (
        home / ".agents" / "AGENTS.md",
        home / ".agents" / "GLOBAL.md",
    )


def _minimax_agent_paths(home: Path) -> tuple[Path, ...]:
    return tuple(
        home / ".minimax" / "agents" / name / "agent.md"
        for name in ("coder", "general", "mavis", "verifier")
    )


def write_global_adapters(root: Path) -> AdapterReport:
    root = root.resolve()
    target = root / "adapters"
    block = _context_block(root)
    written = [
        _write(target / "AGENTS.md", block),
        _write(target / "CLAUDE.md", block),
        _write(target / "copilot-instructions.md", block),
        _write(target / "kiro-steering-llm-wiki.md", block),
        _write(target / "traerules", block),
        _write(target / "antigravity-agents.md", block),
        _write(target / "antigravity-global.md", block),
        _write(target / "minimax-agent.md", block),
        _write(target / "llm-wiki-shell-context.sh", _shell_context(root)),
        _write(
            target / "adapter-manifest.json",
            json.dumps(
                {
                    "root": str(root),
                    "compact_context": str(root / "llms.txt"),
                    "full_context": str(root / "llms-full.txt"),
                    "manifest": str(root / "llms.json"),
                    "adapters": {
                        "codex": "AGENTS.md",
                        "claude-code": "CLAUDE.md",
                        "github-copilot": "copilot-instructions.md",
                        "kiro": "kiro-steering-llm-wiki.md",
                        "trae": "traerules",
                        "antigravity": "antigravity-agents.md",
                        "antigravity-global": "antigravity-global.md",
                        "minimax": "minimax-agent.md",
                        "shell": "llm-wiki-shell-context.sh",
                    },
                },
                ensure_ascii=False,
                indent=2,
            ),
        ),
    ]
    return AdapterReport(root=root, target=target, written=tuple(written))


def attach_project(root: Path, project: Path) -> AttachReport:
    root = root.resolve()
    project = project.resolve()
    block = _context_block(root, project=project)
    written = [
        _merge_marked_block(project / ".agents" / "AGENTS.md", block),
        _merge_marked_block(project / ".agents" / "GLOBAL.md", block),
        _merge_marked_block(project / "AGENTS.md", block),
        _merge_marked_block(project / "CLAUDE.md", block),
        _merge_marked_block(project / ".github" / "copilot-instructions.md", block),
        _merge_marked_block(project / ".kiro" / "steering" / "llm-wiki.md", block),
        _merge_marked_block(project / ".traerules", block),
        _write(project / ".llm-wiki" / "shell-context.sh", _shell_context(root)),
        _write(
            project / ".llm-wiki" / "context.json",
            json.dumps(
                {
                    "wiki_root": str(root),
                    "llms_txt": str(root / "llms.txt"),
                    "llms_full_txt": str(root / "llms-full.txt"),
                    "llms_json": str(root / "llms.json"),
                    "project": str(project),
                },
                ensure_ascii=False,
                indent=2,
            ),
        ),
    ]
    return AttachReport(root=root, project=project, written=tuple(written))



def install_global_adapters(root: Path, *, home: Path | None = None) -> AttachReport:
    root = root.resolve()
    home = (home or Path.home()).expanduser().resolve()
    block = _context_block(root)
    shell_source = f"""{MARKER_START}
# LLM Wiki shell context
if [ -f {str(root / 'adapters' / 'llm-wiki-shell-context.sh')!r} ]; then
  source {str(root / 'adapters' / 'llm-wiki-shell-context.sh')!r}
fi
{MARKER_END}
"""
    written = [
        *(_merge_marked_block(path, block) for path in _antigravity_global_paths(home)),
        *(_merge_marked_block(path, block) for path in _minimax_agent_paths(home)),
        _merge_marked_block(home / ".codex" / "AGENTS.md", block),
        _merge_marked_block(home / "CLAUDE.md", block),
        _merge_marked_block(home / ".traerules", block),
        _merge_marked_block(home / ".kiro" / "steering" / "llm-wiki.md", block),
        _merge_marked_block(home / ".zshrc", shell_source),
        _write(home / ".config" / "lwiki" / "context.json", json.dumps(
            {
                "wiki_root": str(root),
                "llms_txt": str(root / "llms.txt"),
                "llms_full_txt": str(root / "llms-full.txt"),
                "llms_json": str(root / "llms.json"),
                "adapters": str(root / "adapters"),
            },
            ensure_ascii=False,
            indent=2,
        )),
    ]
    return AttachReport(root=root, project=home, written=tuple(written))


def render_adapter_report(report: AdapterReport) -> str:
    lines = [
        f"# Adapter Report — {report.root.name}",
        "",
        f"- Adapter directory: {report.target}",
        f"- Files written: {len(report.written)}",
        "",
        "## Written Files",
    ]
    lines.extend(f"- `{path}`" for path in report.written)
    return "\n".join(lines)


def render_attach_report(report: AttachReport) -> str:
    lines = [
        f"# Attach Report — {report.project.name}",
        "",
        f"- Wiki root: {report.root}",
        f"- Project: {report.project}",
        f"- Files written: {len(report.written)}",
        "",
        "## Written Files",
    ]
    lines.extend(f"- `{path}`" for path in report.written)
    return "\n".join(lines)
